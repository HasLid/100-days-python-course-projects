# loops through a list of fruits and prints each one

fruits = ["apple", "banana", "cherry", "date", "elderberry"]
for fruit in fruits:
    print(fruit)
# print a "i love" message for each fruit
    print("I love " + fruit + "!")
# print a separator line
    print("----------")
# to add messages to fruits, you can use the + operator to concatenate strings
    print(fruit + "and orange are my favorite fruits.")
